export function calculateDfmConfidence({ layers = 2, minTraceMil = 4, surfaceFinish = 'ENIG (Gold)', bgaInspection = true }) {
  let score = 99.8;
  const factors = [];

  if (minTraceMil <= 3) {
    score -= 3.2;
    factors.push({ rule: "3/3 mil Ultra-Fine Trace", status: "LDI Laser Direct Imaging required", impact: "-3.2%" });
  } else {
    factors.push({ rule: "Standard Trace Clearance (≥4 mil)", status: "Optimal process capability window", impact: "+0.0%" });
  }

  if (layers >= 8) {
    score -= 1.2;
    factors.push({ rule: `${layers}-Layer Lamination`, status: "Sequential pressing with X-ray layer alignment", impact: "-1.2%" });
  }

  if (surfaceFinish.includes('Gold') || surfaceFinish.includes('ENIG')) {
    score += 0.8;
    factors.push({ rule: "Electroless Nickel Immersion Gold (ENIG)", status: "Planar surface with superior SMT wetting", impact: "+0.8%" });
  }

  if (bgaInspection) {
    score += 1.4;
    factors.push({ rule: "160kV Nordson X-Ray CT Inspection", status: "Sub-micron voiding & bridging verified", impact: "+1.4%" });
  }

  const normalized = Math.min(99.9, Math.max(92.0, score)).toFixed(1);
  return {
    score: normalized,
    processWindow: normalized >= 98 ? "AS9100D Class 3 Guaranteed" : "IPC Class 2 Controlled",
    riskLevel: normalized >= 98 ? "Optimal Cleanroom Yield" : "Tight Tolerance Run",
    factors
  };
}
